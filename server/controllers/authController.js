const resetPassword = async (req, res) => {
  const { identifier, password } = req.body;
  
  if (!identifier || !password) {
    return res.status(400).json({ error: 'Missing required fields' });
  }

  const cleaned = identifier.trim().toLowerCase();

  if (!isVerified(cleaned)) {
    return res.status(400).json({ error: 'Please verify your OTP first' });
  }

  const passwordRegex = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&._#\^+-]).{8,}$/;
  if (!passwordRegex.test(password)) {
    return res.status(400).json({ error: 'Password must be at least 8 chars and include uppercase, lowercase, number, and symbol' });
  }

  const hashedPassword = await hashPassword(password);

  try {
    const user = await prisma.user.findFirst({
      where: { OR: [{ email: cleaned }, { phone: cleaned }] }
    });

    if (!user) return res.status(404).json({ error: 'User not found' });

    await prisma.user.update({
      where: { id: user.id },
      data: { passwordHash: hashedPassword }
    });

    clearOTP(cleaned);

    res.json({ message: 'Password reset successfully' });
  } catch (err) {
    console.error('Reset password error:', err);
    res.status(500).json({ error: 'Failed to reset password' });
  }
};

// ─── Guest Login ─────────────────────────────────────────────────────────
const guestLogin = async (req, res) => {
  try {
    const guestEmail = 'guest@expenseiq.local';
    let user = await prisma.user.findFirst({ where: { email: guestEmail } });
    
    if (!user) {
      user = await prisma.user.create({
        data: {
          name: 'Guest User',
          email: guestEmail,
        }
      });
    }
    
    res.json({
      id: user.id,
      name: user.name,
      email: user.email,
      token: generateToken(user.id),
      isGuest: true
    });
  } catch (error) {
    console.error('Guest login error:', error);
    res.status(500).json({ error: 'Server error during guest login' });
  }
};

